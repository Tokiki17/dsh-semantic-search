export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string

export function translator(language: string | undefined): Translate {
  const table: Record<MessageKey, string> = language?.toLowerCase().startsWith('zh') ? zh : en
  return (key, values) => format(table[key], values)
}

function format(template: string, values: Record<string, string | number> | undefined): string {
  return values === undefined ? template : template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match))
}

export function formatBytes(bytes: number): string {
  if (bytes <= 0) return '0 MB'
  if (bytes >= 1 << 30) return `${(bytes / (1 << 30)).toFixed(1)} GB`
  if (bytes >= 1 << 20) return `${Math.round(bytes / (1 << 20))} MB`
  return `${Math.max(1, Math.round(bytes / 1024))} KB`
}
